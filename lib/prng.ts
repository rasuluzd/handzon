/**
 * Deterministisk pseudotilfeldighet. Samme input gir alltid samme resultat, så
 * demoen oppfører seg som ekte data: tidsluker, ordrelister og nøkkeltall er
 * stabile mellom server og klient og mellom hver last.
 */

/** mulberry32 — liten, rask og deterministisk. */
export function mulberry32(seed: number): () => number {
  let state = seed;
  return () => {
    state |= 0;
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** FNV-1a. */
export function hashString(value: string): number {
  let hash = 2166136261;
  for (let i = 0; i < value.length; i += 1) {
    hash ^= value.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}
